def format_scalar(value):
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str):
        return f'"{value}"'
    return str(value)


def dump_yaml(node, indent=0):
    lines = []
    prefix = " " * indent

    if isinstance(node, dict):
        for key, value in node.items():
            if isinstance(value, dict):
                lines.append(f"{prefix}{key}:")
                lines.extend(dump_yaml(value, indent + 2))
            elif isinstance(value, list):
                inline = ", ".join(format_scalar(item) for item in value)
                lines.append(f"{prefix}{key}: [{inline}]")
            else:
                lines.append(f"{prefix}{key}: {format_scalar(value)}")
    else:
        raise TypeError(f"Unsupported YAML node: {type(node)!r}")

    return lines


