    cfg = deepcopy(BASE_CONFIG)
    ablation = cfg["TRAINER"]["GSPA_LEGACY"]["ABLATION"]
    ablation.update(spec)
    cfg["TRAINER"]["GSPA_LEGACY"]["STATS_SCOPE"] = spec["STATS_SCOPE"]
    return cfg


